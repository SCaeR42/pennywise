/**
 * Тип финансовой транзакции
 * - `expense` — расход (списание средств)
 * - `income` — доход (зачисление средств)
 * - `transfer` — перевод между счетами
 */
export type TransactionType = 'expense' | 'income' | 'transfer';

/**
 * Основная сущность финансовой транзакции
 * Используется для учёта расходов, доходов и переводов
 */
export interface Transaction {
  /** Уникальный идентификатор транзакции (UUID) */
  id: string;
  /** Дата транзакции в формате ISO 8601 (YYYY-MM-DD) */
  date: string;
  /** Сумма транзакции (положительное число) */
  amount: number;
  /** Тип транзакции: расход, доход или перевод */
  type: TransactionType;
  /** ID счёта-источника (обязателен для expense/transfer) */
  sourceAccountId?: string;
  /** ID счёта-назначения (обязателен для transfer) */
  destinationAccountId?: string;
  /** ID категории, к которой относится транзакция */
  categoryId: string;
  /** Массив ID тегов для дополнительной классификации */
  tagIds: string[];
  /** Произвольный комментарий к транзакции */
  comment: string;
  /** Дата и время создания записи (ISO 8601, автогенерация) */
  createdAt: string;
}

/**
 * Категория для классификации транзакций
 * (например: «Продукты», «Транспорт», «Зарплата»)
 */
export interface Category {
  /** Уникальный идентификатор категории (UUID) */
  id: string;
  /** Отображаемое название категории */
  name: string;
  /** Опциональная иконка (название из набора иконок или SVG) */
  icon?: string;
}

/**
 * Финансовый счёт пользователя
 * (например: банковская карта, наличные, накопительный счёт)
 */
export interface Account {
  /** Уникальный идентификатор счёта (UUID) */
  id: string;
  /** Отображаемое название счёта */
  name: string;
  /** Код валюты в формате ISO 4217 (например: 'RUB', 'USD', 'EUR') */
  currency: string;
  /** Текущий баланс счёта (может быть отрицательным для кредитных) */
  balance: number;
}

/**
 * Тег для дополнительной маркировки транзакций
 * Позволяет гибко группировать записи поверх категорий
 */
export interface Tag {
  /** Уникальный идентификатор тега (UUID) */
  id: string;
  /** Название тега */
  name: string;
  /** Цвет тега в HEX-формате (например: '#FF5733') */
  color: string;
}

/**
 * Пользовательские настройки интерфейса
 */
export interface UserSettings {
  /** Количество строк на странице в таблицах */
  rowsPerPage: number;
  /** Тема оформления: светлая, тёмная или системная */
  theme: 'light' | 'dark' | 'system';
  /** URL или путь к аватару пользователя (опционально) */
  avatar?: string;
  /** Состояние сворачивания боковой панели */
  sideBarCollapsed: boolean;
}

/**
 * Тарифный план подписки
 * Используется на странице Pricing для отображения доступных планов
 */
export interface PricingPlan {
  /** Уникальный идентификатор плана (UUID) */
  id: string;
  /** Отображаемое название плана (например: «Pro», «Business») */
  name: string;
  /** Стоимость плана (число) */
  price: number;
  /** Период оплаты (например: 'month', 'year') */
  period: string;
  /** Список включённых функций/возможностей плана */
  features: string[];
  /** Флаг популярности — для выделения рекомендуемого плана */
  popular?: boolean;
}

/**
 * Запись об оплате подписки
 * Используется в истории платежей пользователя
 */
export interface BillingRecord {
  /** Уникальный идентификатор записи об оплате (UUID) */
  id: string;
  /** Дата оплаты в формате ISO 8601 (YYYY-MM-DD) */
  date: string;
  /** Сумма оплаты */
  amount: number;
  /** Название тарифного плана, за который была произведена оплата */
  planName: string;
  /** Статус платежа: оплачен, ожидает или ошибка */
  status: 'paid' | 'pending' | 'failed';
}
